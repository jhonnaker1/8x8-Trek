#!/usr/bin/env python3
"""Write the Finder icon's resources (ICN# and icl4) as Rez source.

usage: mkicon.py OUT.r        write build/icon.r, #included by src/egatrek.r
       mkicon.py --sheet      print the artwork back, to be looked at

THE ARTWORK IS THIS PROJECT'S OWN, and the same design as the Amiga's
Workbench icon (amiga/tools/mkicon.py): the ship as the game's own badge
draws it -- a saucer, a neck and a hull -- computed as ellipses with exact
centres and radii, so it is symmetrical because it is computed to be. That
file found hand-laid ASCII read as a blob at icon size; so does this one.

TWO RESOURCES, because the Finder has two kinds of screen. ICN# is the
black-and-white icon and its mask, which every Finder reads; icl4 is the
16-colour one System 7 draws on a colour screen, in the Finder's own 4-bit
palette (not EGA's -- an icon is drawn by the Finder, not by the game).
"""
import sys

W = H = 32

# Pens: '.' transparent, '#' black, 'o' white, '*' blue (windows).
def art():
    g = [["."] * W for _ in range(H)]

    def ellipse(cx, cy, rx, ry, pen):
        for y in range(H):
            for x in range(W):
                if ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1.0:
                    g[y][x] = pen

    # A white disc behind the ship, so it reads on any desktop pattern.
    ellipse(16, 16, 15.5, 15.5, "o")
    ellipse(16, 16, 15.5, 15.5, "#")
    ellipse(16, 16, 14.5, 14.5, "o")
    ellipse(16, 11.5, 11.0, 3.0, "#")          # the saucer
    ellipse(16, 21.0, 6.5, 2.4, "#")           # the hull
    for y in range(13, 20):                    # the neck
        for x in range(15, 17):
            g[y][x] = "#"
    ellipse(16, 11.5, 8.0, 0.9, "*")           # a band of windows
    return g


# The Finder's standard 4-bit palette (System 7): 0 white ... 6 blue ... 15 black.
ICL4 = {".": 0, "o": 0, "#": 15, "*": 6}


def bits(g, on):
    rows = []
    for y in range(H):
        v = 0
        for x in range(W):
            if g[y][x] in on:
                v |= 1 << (31 - x)
        rows.append(v)
    return rows


def hexrows(words, per_line=4):
    out = []
    for i in range(0, len(words), per_line):
        out.append('\t\t$"' + " ".join("%08X" % w for w in words[i:i + per_line]) + '"')
    return "\n".join(out)


def main():
    g = art()
    if len(sys.argv) > 1 and sys.argv[1] == "--sheet":
        for row in g:
            print("".join(row))
        return
    out = sys.argv[1]
    icon = bits(g, "#*")                       # black where not white: windows too
    mask = bits(g, "#*o")
    nibbles = []
    for y in range(H):
        for x in range(0, W, 8):
            v = 0
            for k in range(8):
                v = (v << 4) | ICL4[g[y][x + k]]
            nibbles.append(v)
    with open(out, "w") as f:
        f.write("/* GENERATED by mac/tools/mkicon.py -- do not edit. */\n\n")
        f.write("resource 'ICN#' (128) {\n\t{\n\t\t/* icon */\n")
        f.write(hexrows(icon) + ",\n\t\t/* mask */\n" + hexrows(mask) + "\n\t}\n};\n\n")
        f.write("data 'icl4' (128) {\n" + hexrows(nibbles) + "\n};\n")


main()
